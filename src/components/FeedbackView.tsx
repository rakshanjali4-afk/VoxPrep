import React, { useState } from 'react';
import {
  Award,
  CheckCircle2,
  AlertTriangle,
  BookOpen,
  Download,
  Printer,
  RotateCcw,
  Sparkles,
  ChevronDown,
  ChevronUp,
  Clock,
  ArrowRight,
  TrendingUp,
  Brain,
  MessageSquare,
  Target,
  Share2,
} from 'lucide-react';
import { FeedbackReport } from '../types/interview';

interface FeedbackViewProps {
  report: FeedbackReport;
  onTryAgain: () => void;
  onPracticeWeakTopics: (topics: string[]) => void;
  onBackToDashboard: () => void;
}

export const FeedbackView: React.FC<FeedbackViewProps> = ({
  report,
  onTryAgain,
  onPracticeWeakTopics,
  onBackToDashboard,
}) => {
  const [expandedIndex, setExpandedIndex] = useState<number | null>(0);
  const [copiedLink, setCopiedLink] = useState(false);

  // Score tier descriptor
  const getRatingTier = (score: number) => {
    if (score >= 90) return { label: 'Exceptional (Top 5%)', color: 'text-emerald-400 bg-emerald-500/10 border-emerald-500/30' };
    if (score >= 80) return { label: 'Strong Hire', color: 'text-purple-400 bg-purple-500/10 border-purple-500/30' };
    if (score >= 70) return { label: 'Solid Candidate', color: 'text-blue-400 bg-blue-500/10 border-blue-500/30' };
    return { label: 'Needs Practice', color: 'text-amber-400 bg-amber-500/10 border-amber-500/30' };
  };

  const rating = getRatingTier(report.overallScore);

  // Download Report as Markdown/Text file
  const handleDownloadReport = () => {
    const markdownContent = `# VoxPrep Interview Report
**Role:** ${report.role} (${report.level})
**Interview Type:** ${report.type}
**Date:** ${new Date(report.date).toLocaleDateString()}
**Session Duration:** ${Math.round(report.durationSeconds / 60)} minutes
**Overall Score:** ${report.overallScore} / 100 (${rating.label})

---

## Performance Summary
${report.summary}

## Core Competency Scores
- **Technical Knowledge:** ${report.technicalScore} / 100
- **Communication Clarity:** ${report.clarityScore} / 100
- **Relevance of Answers:** ${report.relevanceScore} / 100
- **Problem-Solving & Trade-offs:** ${report.problemSolvingScore} / 100

## Key Strengths
${report.strengths.map((s) => `- ${s}`).join('\n')}

## Areas for Improvement
${report.areasForImprovement.map((a) => `- ${a}`).join('\n')}

---

## Detailed Question-by-Question Breakdown
${report.questionFeedback
  .map(
    (q, i) => `### Question ${i + 1}: ${q.question}
**Candidate Answer:** ${q.answer}
**Score:** ${q.score}/100
**Strengths:** ${q.strengths}
**Critique:** ${q.critique}
**Model Exemplary Answer:** ${q.idealAnswer}
`
  )
  .join('\n\n')}

---

## Recommended Topics to Study
${report.recommendedTopics.map((t) => `- ${t}`).join('\n')}

Generated by VoxPrep — "Speak with confidence. Interview with success."
`;

    const blob = new Blob([markdownContent], { type: 'text/markdown;charset=utf-8;' });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    link.setAttribute('download', `VoxPrep_Report_${report.role.replace(/\s+/g, '_')}_${report.overallScore}pts.md`);
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
  };

  // Print Report
  const handlePrint = () => {
    window.print();
  };

  return (
    <div className="mx-auto max-w-5xl px-4 py-8 sm:px-6 lg:px-8 print-page">
      {/* Top action row */}
      <div className="mb-6 flex flex-wrap items-center justify-between gap-4 no-print">
        <button
          onClick={onBackToDashboard}
          className="text-xs font-medium text-slate-400 hover:text-white transition-colors"
        >
          ← Back to Dashboard
        </button>

        <div className="flex items-center gap-2">
          <button
            onClick={handleDownloadReport}
            className="flex items-center gap-1.5 rounded-lg border border-slate-800 bg-slate-900/60 px-3 py-1.5 text-xs font-medium text-slate-300 hover:bg-slate-800 hover:text-white transition-colors"
          >
            <Download className="h-3.5 w-3.5 text-purple-400" />
            <span>Download Report</span>
          </button>

          <button
            onClick={handlePrint}
            className="flex items-center gap-1.5 rounded-lg border border-slate-800 bg-slate-900/60 px-3 py-1.5 text-xs font-medium text-slate-300 hover:bg-slate-800 hover:text-white transition-colors"
          >
            <Printer className="h-3.5 w-3.5 text-slate-400" />
            <span>Print Report</span>
          </button>

          <button
            onClick={onTryAgain}
            className="flex items-center gap-1.5 rounded-lg bg-purple-600 px-3.5 py-1.5 text-xs font-semibold text-white hover:bg-purple-500 shadow-md shadow-purple-600/20 transition-all"
          >
            <RotateCcw className="h-3.5 w-3.5" />
            <span>Try Again</span>
          </button>
        </div>
      </div>

      {/* Main Score Hero Card */}
      <div className="rounded-2xl border border-slate-800 bg-gradient-to-b from-slate-900/80 via-slate-900/50 to-slate-950 p-6 sm:p-8 shadow-xl">
        <div className="flex flex-col md:flex-row md:items-center md:justify-between gap-6 pb-6 border-b border-slate-800">
          <div>
            <div className="flex items-center gap-2">
              <span className={`px-2.5 py-0.5 rounded-md text-xs font-semibold border ${rating.color}`}>
                {rating.label}
              </span>
              {report.isDemo && (
                <span className="px-2 py-0.5 rounded-md text-xs font-medium bg-amber-500/10 text-amber-400 border border-amber-500/20">
                  Demo Session
                </span>
              )}
            </div>
            <h1 className="mt-2 text-2xl sm:text-3xl font-bold tracking-tight text-white">
              {report.role} Interview Report
            </h1>
            <p className="mt-1 text-xs sm:text-sm text-slate-400">
              Level: {report.level} · Format: {report.type} · Duration: {Math.round(report.durationSeconds / 60)} min · Completed on {new Date(report.date).toLocaleDateString()}
            </p>
          </div>

          {/* Overall Score Dial */}
          <div className="flex items-center gap-4 bg-slate-950/80 border border-slate-800 rounded-2xl p-4 shrink-0">
            <div className="relative flex h-20 w-20 items-center justify-center rounded-full bg-slate-900 border-4 border-purple-500 shadow-inner">
              <div className="text-center">
                <div className="text-2xl font-bold tracking-tight text-white font-mono tabular-nums">
                  {report.overallScore}
                </div>
                <div className="text-[10px] text-slate-400 uppercase font-semibold">out of 100</div>
              </div>
            </div>
            <div>
              <div className="text-xs font-semibold text-slate-200">Overall Readiness</div>
              <div className="text-xs text-slate-400 mt-0.5">Based on complete transcript</div>
            </div>
          </div>
        </div>

        {/* 4 Competency Score Meters */}
        <div className="mt-6 grid grid-cols-2 gap-4 sm:grid-cols-4">
          <div className="rounded-xl border border-slate-800/80 bg-slate-950/40 p-4">
            <div className="flex items-center justify-between text-xs text-slate-400">
              <div className="flex items-center gap-1.5">
                <Brain className="h-3.5 w-3.5 text-purple-400" />
                <span>Technical</span>
              </div>
              <span className="font-mono font-bold text-white tabular-nums">
                {report.technicalScore}%
              </span>
            </div>
            <div className="mt-2 h-1.5 w-full overflow-hidden rounded-full bg-slate-800">
              <div
                className="h-full bg-purple-500 transition-all duration-500"
                style={{ width: `${report.technicalScore}%` }}
              />
            </div>
          </div>

          <div className="rounded-xl border border-slate-800/80 bg-slate-950/40 p-4">
            <div className="flex items-center justify-between text-xs text-slate-400">
              <div className="flex items-center gap-1.5">
                <MessageSquare className="h-3.5 w-3.5 text-indigo-400" />
                <span>Clarity</span>
              </div>
              <span className="font-mono font-bold text-white tabular-nums">
                {report.clarityScore}%
              </span>
            </div>
            <div className="mt-2 h-1.5 w-full overflow-hidden rounded-full bg-slate-800">
              <div
                className="h-full bg-indigo-500 transition-all duration-500"
                style={{ width: `${report.clarityScore}%` }}
              />
            </div>
          </div>

          <div className="rounded-xl border border-slate-800/80 bg-slate-950/40 p-4">
            <div className="flex items-center justify-between text-xs text-slate-400">
              <div className="flex items-center gap-1.5">
                <Target className="h-3.5 w-3.5 text-sky-400" />
                <span>Relevance</span>
              </div>
              <span className="font-mono font-bold text-white tabular-nums">
                {report.relevanceScore}%
              </span>
            </div>
            <div className="mt-2 h-1.5 w-full overflow-hidden rounded-full bg-slate-800">
              <div
                className="h-full bg-sky-500 transition-all duration-500"
                style={{ width: `${report.relevanceScore}%` }}
              />
            </div>
          </div>

          <div className="rounded-xl border border-slate-800/80 bg-slate-950/40 p-4">
            <div className="flex items-center justify-between text-xs text-slate-400">
              <div className="flex items-center gap-1.5">
                <TrendingUp className="h-3.5 w-3.5 text-emerald-400" />
                <span>Problem Solving</span>
              </div>
              <span className="font-mono font-bold text-white tabular-nums">
                {report.problemSolvingScore}%
              </span>
            </div>
            <div className="mt-2 h-1.5 w-full overflow-hidden rounded-full bg-slate-800">
              <div
                className="h-full bg-emerald-500 transition-all duration-500"
                style={{ width: `${report.problemSolvingScore}%` }}
              />
            </div>
          </div>
        </div>

        {/* Executive Summary */}
        <div className="mt-6 rounded-xl border border-slate-800/80 bg-slate-950/50 p-4">
          <div className="text-xs font-semibold text-slate-300">Executive Assessment</div>
          <p className="mt-1.5 text-xs sm:text-sm text-slate-300 leading-relaxed">
            {report.summary}
          </p>
        </div>
      </div>

      {/* 2-Column: Strengths vs Areas for Improvement */}
      <div className="mt-8 grid grid-cols-1 gap-6 md:grid-cols-2">
        {/* Strengths */}
        <div className="rounded-2xl border border-slate-800 bg-slate-900/50 p-6 shadow-sm">
          <div className="flex items-center gap-2 font-semibold text-sm text-white">
            <CheckCircle2 className="h-4 w-4 text-emerald-400" />
            <span>Demonstrated Strengths</span>
          </div>
          <ul className="mt-4 space-y-3">
            {report.strengths.map((str, idx) => (
              <li key={idx} className="flex items-start gap-2.5 text-xs text-slate-300 leading-relaxed">
                <span className="flex h-4 w-4 shrink-0 items-center justify-center rounded-full bg-emerald-500/20 text-emerald-400 text-[10px] font-bold mt-0.5">
                  ✓
                </span>
                <span>{str}</span>
              </li>
            ))}
          </ul>
        </div>

        {/* Areas for Improvement */}
        <div className="rounded-2xl border border-slate-800 bg-slate-900/50 p-6 shadow-sm">
          <div className="flex items-center gap-2 font-semibold text-sm text-white">
            <AlertTriangle className="h-4 w-4 text-amber-400" />
            <span>Targeted Areas for Improvement</span>
          </div>
          <ul className="mt-4 space-y-3">
            {report.areasForImprovement.map((area, idx) => (
              <li key={idx} className="flex items-start gap-2.5 text-xs text-slate-300 leading-relaxed">
                <span className="flex h-4 w-4 shrink-0 items-center justify-center rounded-full bg-amber-500/20 text-amber-400 text-[10px] font-bold mt-0.5">
                  !
                </span>
                <span>{area}</span>
              </li>
            ))}
          </ul>
        </div>
      </div>

      {/* Detailed Question-by-Question Breakdown */}
      <div className="mt-8 space-y-4">
        <div className="flex items-center justify-between">
          <div>
            <h2 className="text-lg font-bold text-white">Detailed Question Breakdown</h2>
            <p className="text-xs text-slate-400">
              Review every answer you provided, the examiner critique, and the top-tier model response.
            </p>
          </div>
        </div>

        <div className="space-y-3">
          {report.questionFeedback.map((item, idx) => {
            const isExpanded = expandedIndex === idx;
            return (
              <div
                key={idx}
                className="rounded-xl border border-slate-800 bg-slate-900/40 overflow-hidden transition-all"
              >
                {/* Accordion Header */}
                <button
                  onClick={() => setExpandedIndex(isExpanded ? null : idx)}
                  className="w-full flex items-center justify-between p-4 text-left hover:bg-slate-800/40 transition-colors"
                >
                  <div className="flex items-center gap-3 pr-4">
                    <span className="flex h-7 w-7 items-center justify-center rounded-md bg-slate-800 text-xs font-bold text-slate-300 shrink-0 font-mono">
                      Q{idx + 1}
                    </span>
                    <span className="text-xs sm:text-sm font-semibold text-slate-200 line-clamp-1">
                      {item.question}
                    </span>
                  </div>

                  <div className="flex items-center gap-3 shrink-0">
                    <span className="font-mono text-xs font-semibold text-purple-400 tabular-nums">
                      {item.score}/100
                    </span>
                    {isExpanded ? (
                      <ChevronUp className="h-4 w-4 text-slate-400" />
                    ) : (
                      <ChevronDown className="h-4 w-4 text-slate-400" />
                    )}
                  </div>
                </button>

                {/* Accordion Body */}
                {isExpanded && (
                  <div className="p-4 pt-0 border-t border-slate-800/60 space-y-4 text-xs">
                    {/* Full question */}
                    <div className="text-slate-300 font-medium bg-slate-950/40 p-3 rounded-lg border border-slate-800">
                      <span className="text-purple-400 font-semibold">Question: </span>
                      {item.question}
                    </div>

                    {/* Candidate's answer */}
                    <div className="space-y-1">
                      <div className="text-slate-400 font-semibold">Your Spoken Answer:</div>
                      <div className="text-slate-200 bg-slate-950/60 p-3 rounded-lg border border-slate-800/80 leading-relaxed italic">
                        "{item.answer || '(No answer recorded)'}"
                      </div>
                    </div>

                    {/* Strengths & Critique */}
                    <div className="grid grid-cols-1 sm:grid-cols-2 gap-3">
                      <div className="bg-emerald-950/20 border border-emerald-500/20 p-3 rounded-lg">
                        <div className="font-semibold text-emerald-400 mb-1">What Worked Well:</div>
                        <div className="text-slate-300 leading-relaxed">{item.strengths}</div>
                      </div>
                      <div className="bg-amber-950/20 border border-amber-500/20 p-3 rounded-lg">
                        <div className="font-semibold text-amber-400 mb-1">Examiner Critique:</div>
                        <div className="text-slate-300 leading-relaxed">{item.critique}</div>
                      </div>
                    </div>

                    {/* Exemplary Answer */}
                    <div className="bg-purple-950/20 border border-purple-500/30 p-3.5 rounded-lg space-y-1.5">
                      <div className="flex items-center gap-1.5 font-semibold text-purple-300">
                        <Sparkles className="h-3.5 w-3.5 text-purple-400" />
                        <span>Top Performer Example Answer:</span>
                      </div>
                      <div className="text-slate-200 leading-relaxed">{item.idealAnswer}</div>
                    </div>
                  </div>
                )}
              </div>
            );
          })}
        </div>
      </div>

      {/* Recommended Topics To Study */}
      <div className="mt-8 rounded-2xl border border-slate-800 bg-slate-900/50 p-6 shadow-sm">
        <div className="flex items-center gap-2 font-semibold text-sm text-white">
          <BookOpen className="h-4 w-4 text-purple-400" />
          <span>Recommended Topics to Master Next</span>
        </div>
        <p className="mt-1 text-xs text-slate-400">
          Based on gaps identified in your answers, prioritize studying these subject areas before your real interview:
        </p>
        <div className="mt-4 flex flex-wrap gap-2">
          {report.recommendedTopics.map((topic, i) => (
            <span
              key={i}
              className="rounded-lg border border-purple-500/20 bg-purple-950/30 px-3 py-1.5 text-xs font-medium text-purple-300"
            >
              {topic}
            </span>
          ))}
        </div>

        <div className="mt-6 flex flex-wrap items-center justify-between gap-4 pt-4 border-t border-slate-800">
          <span className="text-xs text-slate-400">
            Want to drill down specifically on these weak topics?
          </span>
          <button
            onClick={() => onPracticeWeakTopics(report.recommendedTopics)}
            className="flex items-center gap-2 rounded-lg bg-indigo-600 px-4 py-2 text-xs font-semibold text-white hover:bg-indigo-500 transition-colors shadow-sm"
          >
            <span>Practice Weak Topics</span>
            <ArrowRight className="h-3.5 w-3.5" />
          </button>
        </div>
      </div>

      {/* Bottom Bar Actions */}
      <div className="mt-8 flex flex-wrap items-center justify-between gap-4 border-t border-slate-800 pt-6 no-print">
        <button
          onClick={onBackToDashboard}
          className="px-4 py-2 text-xs font-medium text-slate-400 hover:text-white transition-colors"
        >
          ← Return to Dashboard
        </button>

        <div className="flex items-center gap-3">
          <button
            onClick={handleDownloadReport}
            className="rounded-lg border border-slate-800 bg-slate-900 px-4 py-2 text-xs font-medium text-slate-300 hover:bg-slate-800 hover:text-white transition-colors"
          >
            Download Markdown Report
          </button>
          <button
            onClick={onTryAgain}
            className="rounded-lg bg-gradient-to-r from-purple-600 to-indigo-600 px-5 py-2 text-xs font-semibold text-white hover:from-purple-500 hover:to-indigo-500 shadow-md transition-all"
          >
            Start Another Interview
          </button>
        </div>
      </div>
    </div>
  );
};
